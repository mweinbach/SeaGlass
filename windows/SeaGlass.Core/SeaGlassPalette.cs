    public static SeaGlassPalette FromId(string? id)
    {
        if (string.IsNullOrWhiteSpace(id)) return SeafoamMint;
        foreach (SeaGlassPalette p in Entries)
        {
            if (string.Equals(p.Id, id, StringComparison.OrdinalIgnoreCase) ||
                string.Equals(p.DisplayName, id, StringComparison.OrdinalIgnoreCase))
            {
                return p;
            }
        }
        return SeafoamMint;
    }

    /// <summary>
    /// Derives a complete harmonized <see cref="SeaGlassPalette"/> from arbitrary Material 3 / Windows accent colors.
    /// </summary>
    public static SeaGlassPalette FromAccentColors(
        int primaryArgb,
        int secondaryArgb,
        int tertiaryArgb,
        int surfaceArgb,
        string displayName = "Dynamic Accent Glass")
    {
        int pTint = SeaGlassColorMath.HarmonizeToSeaGlassPastel(primaryArgb, 0.79f);
        int sTint = SeaGlassColorMath.HarmonizeToSeaGlassPastel(secondaryArgb, 0.81f);
        int tTint = SeaGlassColorMath.HarmonizeToSeaGlassPastel(tertiaryArgb, 0.78f);
        int surfTint = SeaGlassColorMath.HarmonizeToSeaGlassPastel(surfaceArgb, 0.84f);

        return new SeaGlassPalette(
            Id: "dynamic_accent",
            DisplayName: displayName,
            Tagline: "Harmonized Oklab sea-glass palette derived from system accent colors",
            PrimaryGlass: new SeaGlassMaterial(pTint, tintDensity: 0.64f, coarseness: 0.38f, frostRadiusDp: 24f),
